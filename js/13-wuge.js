function wgStrokes(ch) {
  if (WG_STROKES && WG_STROKES[ch] != null) return WG_STROKES[ch];
  return null;
}
function wgWuxing(n) {
  var u = ((n % 10) + 10) % 10;
  if (u === 1 || u === 2) return "木";
  if (u === 3 || u === 4) return "火";
  if (u === 5 || u === 6) return "土";
  if (u === 7 || u === 8) return "金";
  return "水";
}
function wgShuli(n) {
  var m = n % 80;
  return m === 0 ? 80 : m;
}
function wgCalc(name) {
  var chars = name.split('');
  var strokes = [];
  for (var i = 0; i < chars.length; i++) {
    var s = wgStrokes(chars[i]);
    if (s == null) return { error: '「' + chars[i] + '」暂无康熙笔画数据，换个字试试' };
    strokes.push(s);
  }
  var isFuxing = false, xingLen = 1;
  if (chars.length >= 3) {
    var first2 = chars[0] + chars[1];
    if (WG_FUXING.indexOf(first2) >= 0) { isFuxing = true; xingLen = 2; }
  }
  var xing = strokes.slice(0, xingLen);
  var ming = strokes.slice(xingLen);
  var tiange, renge, dige, zongge, waige;
  if (isFuxing) tiange = xing[0] + xing[1];
  else tiange = xing[0] + 1;
  renge = xing[xingLen - 1] + ming[0];
  if (ming.length > 1) dige = ming[0] + ming[1];
  else dige = ming[0] + 1;
  zongge = 0;
  for (var j = 0; j < strokes.length; j++) zongge += strokes[j];
  if (!isFuxing && ming.length === 1) waige = 2;
  else if (isFuxing && ming.length > 1) waige = zongge - renge;
  else waige = zongge - renge + 1;
  var wxT = wgWuxing(tiange), wxR = wgWuxing(renge), wxD = wgWuxing(dige);
  return {
    name: name, chars: chars, strokes: strokes,
    isFuxing: isFuxing, xingLen: xingLen,
    tiange: tiange, renge: renge, dige: dige, zongge: zongge, waige: waige,
    wxT: wxT, wxR: wxR, wxD: wxD,
    sancai: wxT + wxR + wxD
  };
}
function wgGeInfo(n, label) {
  var sl = wgShuli(n);
  var info = WG_81[sl] || ["—","平","暂无释义"];
  return { label: label, num: n, shuli: sl, ming: info[0], jx: info[1], duan: info[2] };
}

