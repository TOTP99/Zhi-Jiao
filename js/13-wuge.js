function submitWugeForm() {
  var inp = document.getElementById('wugeName');
  var name = inp ? inp.value.replace(/\s+/g, '') : '';
  if (!/^[\u4e00-\u9fff]{2,4}$/.test(name)) {
    wugeToForm();
    var el = wugeBody();
    if (el) el.insertAdjacentHTML('afterbegin', '<p class="wuge-err">请输入 2–4 个汉字</p>');
    var inp2 = document.getElementById('wugeName');
    if (inp2) inp2.value = inp ? inp.value : '';
    return;
  }
  var r = wgCalc(name);
  if (r.error) {
    wugeToForm();
    var el2 = wugeBody();
    if (el2) el2.insertAdjacentHTML('afterbegin', '<p class="wuge-err">' + escapeHtml(r.error) + '</p>');
    var inp3 = document.getElementById('wugeName');
    if (inp3) inp3.value = name;
    return;
  }
  _wugeResult = r;
  _wugeJiaoDone = false;
  wugeRenderResult();
}
